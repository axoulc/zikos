//! The Drive-like file tree shared by a conversation.
//!
//! A [`FileTree`] is the materialized view of an ordered event log of
//! [`TreeOp`]s. The log is what actually travels over the wire (as encrypted
//! Matrix room events); every client replays it locally to rebuild the tree.
//! Replay is deterministic: applying the same log in the same order always
//! yields the same tree.

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use thiserror::Error;
use uuid::Uuid;

pub type NodeId = Uuid;

/// The tree root is a fixed, well-known id so that event logs replay
/// identically on every device — the root is never minted randomly.
pub const ROOT_ID: NodeId = Uuid::from_u128(0);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum NodeKind {
    Folder,
    File,
}

/// A file node's reference to its stored blob: the server-minted id, the
/// per-file key, and the take's metadata. The key and metadata travel only
/// inside the end-to-end encrypted room event — never to the blob server
/// (`specs/security.md`, key distribution).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FilePayload {
    /// Blob id under which the ciphertext lives on the blob server.
    pub blob_id: String,
    /// Per-file AES-256 key, base64 on the wire.
    pub key: zikos_crypto::FileKey,
    /// The take's metadata (mirrors the finalized take's `meta.json`).
    pub meta: crate::RecordingMeta,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Node {
    pub id: NodeId,
    pub parent: Option<NodeId>,
    pub kind: NodeKind,
    pub name: String,
    /// Blob reference for file nodes (`None` on folders and on files
    /// authored before file exchange existed).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub file: Option<FilePayload>,
}

/// One mutation of the tree. Serialize these into the room event log.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "op", rename_all = "snake_case")]
pub enum TreeOp {
    /// Create a node. The id is generated by the authoring client so that
    /// replay on other clients converges without a central id mint.
    Create {
        id: NodeId,
        parent: NodeId,
        kind: NodeKind,
        name: String,
        /// Blob reference; present iff the created node is an uploaded
        /// file. Absent on events authored before file exchange existed.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        file: Option<FilePayload>,
    },
    Rename {
        id: NodeId,
        name: String,
    },
    Move {
        id: NodeId,
        new_parent: NodeId,
    },
    /// Delete a node. Cascading: children of a folder are deleted too.
    Delete {
        id: NodeId,
    },
}

#[derive(Debug, Error, PartialEq, Eq)]
pub enum TreeError {
    #[error("unknown node {0}")]
    UnknownNode(NodeId),
    #[error("node {0} is not a folder")]
    NotAFolder(NodeId),
    #[error("invalid name {0:?}: must be 1..=255 chars and contain no '/' or NUL")]
    InvalidName(String),
    #[error("cannot move node {0} under itself")]
    CycleDetected(NodeId),
    #[error("the root node cannot be renamed, moved or deleted")]
    RootImmutable,
    #[error("malformed path {0:?}")]
    MalformedPath(String),
    #[error("file payload is only allowed on file creates")]
    FilePayloadOnFolder,
}

/// A materialized file tree. Nodes are stored in a `BTreeMap` keyed by id so
/// that serialization (and therefore test assertions) are deterministic.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct FileTree {
    pub root: NodeId,
    pub nodes: BTreeMap<NodeId, Node>,
}

impl FileTree {
    /// An empty tree containing only its root folder.
    pub fn new() -> Self {
        let mut nodes = BTreeMap::new();
        nodes.insert(
            ROOT_ID,
            Node {
                id: ROOT_ID,
                parent: None,
                kind: NodeKind::Folder,
                name: String::new(),
                file: None,
            },
        );
        Self {
            root: ROOT_ID,
            nodes,
        }
    }

    /// Apply one op to the tree, enforcing all invariants.
    pub fn apply(&mut self, op: &TreeOp) -> Result<(), TreeError> {
        match op {
            TreeOp::Create {
                id,
                parent,
                kind,
                name,
                file,
            } => {
                Self::check_name(name)?;
                if *kind == NodeKind::Folder && file.is_some() {
                    return Err(TreeError::FilePayloadOnFolder);
                }
                if id == &self.root || self.nodes.contains_key(id) {
                    return Err(TreeError::UnknownNode(*id)); // id collisions are rejected
                }
                let parent_node = self
                    .nodes
                    .get(parent)
                    .ok_or(TreeError::UnknownNode(*parent))?;
                if parent_node.kind != NodeKind::Folder {
                    return Err(TreeError::NotAFolder(*parent));
                }
                self.nodes.insert(
                    *id,
                    Node {
                        id: *id,
                        parent: Some(*parent),
                        kind: *kind,
                        name: name.clone(),
                        file: file.clone(),
                    },
                );
                Ok(())
            }
            TreeOp::Rename { id, name } => {
                Self::check_name(name)?;
                if id == &self.root {
                    return Err(TreeError::RootImmutable);
                }
                let node = self.nodes.get_mut(id).ok_or(TreeError::UnknownNode(*id))?;
                node.name = name.clone();
                Ok(())
            }
            TreeOp::Move { id, new_parent } => {
                if id == &self.root {
                    return Err(TreeError::RootImmutable);
                }
                if id == new_parent || self.is_descendant(*new_parent, *id) {
                    return Err(TreeError::CycleDetected(*id));
                }
                let parent_node = self
                    .nodes
                    .get(new_parent)
                    .ok_or(TreeError::UnknownNode(*new_parent))?;
                if parent_node.kind != NodeKind::Folder {
                    return Err(TreeError::NotAFolder(*new_parent));
                }
                let node = self.nodes.get_mut(id).ok_or(TreeError::UnknownNode(*id))?;
                node.parent = Some(*new_parent);
                Ok(())
            }
            TreeOp::Delete { id } => {
                if id == &self.root {
                    return Err(TreeError::RootImmutable);
                }
                if !self.nodes.contains_key(id) {
                    return Err(TreeError::UnknownNode(*id));
                }
                // Cascade: collect descendants first, then drop them all.
                let doomed: Vec<NodeId> = self
                    .nodes
                    .values()
                    .filter(|n| n.parent == Some(*id))
                    .map(|n| n.id)
                    .collect();
                self.nodes.remove(id);
                for child in doomed {
                    self.apply(&TreeOp::Delete { id: child })?;
                }
                Ok(())
            }
        }
    }

    /// Replay a full event log. Fails on the first invalid op.
    pub fn from_log(ops: &[TreeOp]) -> Result<Self, TreeError> {
        let mut tree = Self::new();
        for op in ops {
            tree.apply(op)?;
        }
        Ok(tree)
    }

    /// The path of a node as a list of names, root excluded.
    pub fn path_of(&self, id: NodeId) -> Result<Vec<String>, TreeError> {
        let mut segments = Vec::new();
        let mut cursor = self.nodes.get(&id).ok_or(TreeError::UnknownNode(id))?;
        while let Some(parent) = cursor.parent {
            segments.push(cursor.name.clone());
            cursor = self
                .nodes
                .get(&parent)
                .ok_or(TreeError::UnknownNode(parent))?;
        }
        segments.reverse();
        Ok(segments)
    }

    /// `/`-joined path, root excluded (e.g. `Takes/Vocal/take-1.flac`).
    pub fn path_string(&self, id: NodeId) -> Result<String, TreeError> {
        Ok(self.path_of(id)?.join("/"))
    }

    /// Resolve a `/`-joined path back to a node id.
    pub fn find_by_path(&self, path: &str) -> Result<Option<NodeId>, TreeError> {
        if path.is_empty() {
            return Ok(Some(self.root));
        }
        if path.starts_with('/') || path.ends_with('/') || path.contains("//") {
            return Err(TreeError::MalformedPath(path.to_string()));
        }
        let mut cursor = self.root;
        for segment in path.split('/') {
            if segment.is_empty() {
                return Err(TreeError::MalformedPath(path.to_string()));
            }
            let next = self
                .nodes
                .values()
                .find(|n| n.parent == Some(cursor) && n.name == segment);
            match next {
                Some(n) => cursor = n.id,
                None => return Ok(None),
            }
        }
        Ok(Some(cursor))
    }

    /// Direct children of a folder, ordered by name.
    pub fn children(&self, folder: NodeId) -> Result<Vec<&Node>, TreeError> {
        let node = self
            .nodes
            .get(&folder)
            .ok_or(TreeError::UnknownNode(folder))?;
        if node.kind != NodeKind::Folder {
            return Err(TreeError::NotAFolder(folder));
        }
        let mut kids: Vec<&Node> = self
            .nodes
            .values()
            .filter(|n| n.parent == Some(folder))
            .collect();
        kids.sort_by(|a, b| a.name.cmp(&b.name));
        Ok(kids)
    }

    fn is_descendant(&self, candidate: NodeId, ancestor: NodeId) -> bool {
        let mut cursor = self.nodes.get(&candidate);
        while let Some(node) = cursor {
            match node.parent {
                Some(parent) if parent == ancestor => return true,
                Some(parent) => cursor = self.nodes.get(&parent),
                None => return false,
            }
        }
        false
    }

    fn check_name(name: &str) -> Result<(), TreeError> {
        let valid = (1..=255).contains(&name.chars().count())
            && !name.contains('/')
            && !name.contains('\0');
        if valid {
            Ok(())
        } else {
            Err(TreeError::InvalidName(name.to_string()))
        }
    }
}

/// A representative [`FilePayload`] for tests (fresh random key).
#[cfg(test)]
pub(crate) fn file_payload() -> FilePayload {
    FilePayload {
        blob_id: "5f0f7f65-1d2e-4c8b-9a7d-0b1c2d3e4f5a".into(),
        key: zikos_crypto::FileKey::generate(),
        meta: crate::RecordingMeta {
            title: "take-20261022-1015".into(),
            format: crate::AudioFormat::Flac,
            started_at: 1_776_000_000,
            duration_secs: 94.5,
            sample_rate_hz: 48_000,
            channels: 2,
            bpm: None,
            comment: None,
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn folder(tree: &mut FileTree, parent: NodeId, name: &str) -> NodeId {
        let id = Uuid::new_v4();
        tree.apply(&TreeOp::Create {
            id,
            parent,
            kind: NodeKind::Folder,
            name: name.into(),
            file: None,
        })
        .unwrap();
        id
    }

    fn file(tree: &mut FileTree, parent: NodeId, name: &str) -> NodeId {
        let id = Uuid::new_v4();
        tree.apply(&TreeOp::Create {
            id,
            parent,
            kind: NodeKind::File,
            name: name.into(),
            file: None,
        })
        .unwrap();
        id
    }

    #[test]
    fn new_tree_has_only_root_with_fixed_id() {
        let tree = FileTree::new();
        assert_eq!(tree.root, ROOT_ID);
        assert_eq!(tree.nodes.len(), 1);
        assert!(matches!(tree.nodes[&tree.root].kind, NodeKind::Folder));
        assert_eq!(tree.nodes[&tree.root].parent, None);
    }

    #[test]
    fn build_tree_and_resolve_paths() {
        let mut tree = FileTree::new();
        let root = tree.root;
        let takes = folder(&mut tree, root, "Takes");
        let vocal = folder(&mut tree, takes, "Vocal");
        let take1 = file(&mut tree, vocal, "take-1.flac");

        assert_eq!(tree.path_string(take1).unwrap(), "Takes/Vocal/take-1.flac");
        assert_eq!(
            tree.find_by_path("Takes/Vocal/take-1.flac").unwrap(),
            Some(take1)
        );
        assert_eq!(tree.find_by_path("Takes/Missing").unwrap(), None);
        assert_eq!(
            tree.children(takes)
                .unwrap()
                .iter()
                .map(|n| n.name.as_str())
                .collect::<Vec<_>>(),
            ["Vocal"]
        );
    }

    #[test]
    fn replaying_a_log_rebuilds_the_same_tree() {
        let mut ops = Vec::new();
        let mut tree = FileTree::new();
        let takes = NodeId::new_v4();
        ops.push(TreeOp::Create {
            id: takes,
            parent: tree.root,
            kind: NodeKind::Folder,
            name: "Takes".into(),
            file: None,
        });
        let f = NodeId::new_v4();
        ops.push(TreeOp::Create {
            id: f,
            parent: takes,
            kind: NodeKind::File,
            name: "old.flac".into(),
            file: None,
        });
        ops.push(TreeOp::Rename {
            id: f,
            name: "take-1.flac".into(),
        });

        for op in &ops {
            tree.apply(op).unwrap();
        }
        let replayed = FileTree::from_log(&ops).unwrap();
        assert_eq!(tree, replayed);
    }

    #[test]
    fn move_rejects_cycles() {
        let mut tree = FileTree::new();
        let root = tree.root;
        let a = folder(&mut tree, root, "a");
        let b = folder(&mut tree, a, "b");
        // Moving `a` under its own descendant must fail.
        assert_eq!(
            tree.apply(&TreeOp::Move {
                id: a,
                new_parent: b
            }),
            Err(TreeError::CycleDetected(a))
        );
        // But moving `b` up to the root is fine.
        assert!(
            tree.apply(&TreeOp::Move {
                id: b,
                new_parent: root
            })
            .is_ok()
        );
    }

    #[test]
    fn delete_cascades_to_children() {
        let mut tree = FileTree::new();
        let root = tree.root;
        let takes = folder(&mut tree, root, "Takes");
        let vocal = folder(&mut tree, takes, "Vocal");
        file(&mut tree, vocal, "take-1.flac");
        file(&mut tree, vocal, "take-2.flac");

        tree.apply(&TreeOp::Delete { id: takes }).unwrap();
        assert!(!tree.nodes.contains_key(&takes));
        assert!(!tree.nodes.contains_key(&vocal));
        assert_eq!(tree.nodes.len(), 1); // only the root remains
    }

    #[test]
    fn invalid_names_and_missing_parents_are_rejected() {
        let mut tree = FileTree::new();
        let root = tree.root;
        assert_eq!(
            tree.apply(&TreeOp::Create {
                id: Uuid::new_v4(),
                parent: root,
                kind: NodeKind::Folder,
                name: "a/b".into(),
                file: None,
            }),
            Err(TreeError::InvalidName("a/b".into()))
        );
        let ghost = Uuid::new_v4();
        assert_eq!(
            tree.apply(&TreeOp::Create {
                id: Uuid::new_v4(),
                parent: ghost,
                kind: NodeKind::Folder,
                name: "ok".into(),
                file: None,
            }),
            Err(TreeError::UnknownNode(ghost))
        );
        let file_id = Uuid::new_v4();
        tree.apply(&TreeOp::Create {
            id: file_id,
            parent: root,
            kind: NodeKind::File,
            name: "f.flac".into(),
            file: None,
        })
        .unwrap();
        // A file cannot be a parent.
        assert!(matches!(
            tree.apply(&TreeOp::Create {
                id: Uuid::new_v4(),
                parent: file_id,
                kind: NodeKind::File,
                name: "nested.flac".into(),
                file: None,
            }),
            Err(TreeError::NotAFolder(_))
        ));
        // The root is immutable.
        assert_eq!(
            tree.apply(&TreeOp::Rename {
                id: root,
                name: "x".into()
            }),
            Err(TreeError::RootImmutable)
        );
    }

    #[test]
    fn tree_serializes_deterministically() {
        let mut tree = FileTree::new();
        let root = tree.root;
        let takes = folder(&mut tree, root, "Takes");
        file(&mut tree, takes, "take-1.flac");
        file(&mut tree, takes, "take-2.flac");

        let json_a = serde_json::to_string(&tree).unwrap();
        let round: FileTree = serde_json::from_str(&json_a).unwrap();
        assert_eq!(tree, round);
        assert_eq!(json_a, serde_json::to_string(&round).unwrap());
    }

    #[test]
    fn file_create_carries_its_payload() {
        let mut tree = FileTree::new();
        let id = Uuid::new_v4();
        let payload = file_payload();
        let op = TreeOp::Create {
            id,
            parent: tree.root,
            kind: NodeKind::File,
            name: "take-1.flac".into(),
            file: Some(payload.clone()),
        };
        tree.apply(&op).unwrap();
        assert_eq!(tree.nodes[&id].file.as_ref(), Some(&payload));

        // The op round-trips through JSON with the key in its base64 form.
        let json = serde_json::to_value(&op).unwrap();
        assert_eq!(json["file"]["blob_id"], payload.blob_id);
        assert!(json["file"]["key"].is_string());
        assert_eq!(serde_json::from_value::<TreeOp>(json).unwrap(), op);
    }

    #[test]
    fn legacy_creates_without_payload_replay_unchanged() {
        // Wire form authored before file payloads existed: no "file" key.
        let id = Uuid::new_v4();
        let json = serde_json::json!({
            "op": "create",
            "id": id.to_string(),
            "parent": ROOT_ID.to_string(),
            "kind": "file",
            "name": "old.flac",
        });
        let op: TreeOp = serde_json::from_value(json).unwrap();
        assert!(
            matches!(&op, TreeOp::Create { file: None, .. }),
            "legacy creates deserialize without a payload"
        );
        let mut tree = FileTree::new();
        tree.apply(&op).unwrap();
        assert_eq!(tree.nodes.len(), 2);
        assert!(tree.nodes[&id].file.is_none());
    }

    #[test]
    fn folder_create_with_file_payload_is_rejected() {
        let mut tree = FileTree::new();
        let before = tree.clone();
        assert_eq!(
            tree.apply(&TreeOp::Create {
                id: Uuid::new_v4(),
                parent: tree.root,
                kind: NodeKind::Folder,
                name: "Takes".into(),
                file: Some(file_payload()),
            }),
            Err(TreeError::FilePayloadOnFolder)
        );
        assert_eq!(tree, before, "a rejected create must not touch the tree");
    }
}
